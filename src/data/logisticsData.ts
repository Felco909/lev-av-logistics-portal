export type TransportMode = 'road' | 'air' | 'sea' | 'rail';
export type FlowDirection = 'export' | 'import' | 'both';
export type RouteCategory = 'europe' | 'russia' | 'cis' | 'caucasus' | 'iran' | 'asia';

export interface Destination {
  id: string;
  name: string;
  nameEn: string;
  countryCode: string;
  category: RouteCategory;
  lat: number;
  lng: number;
  isArmeniaHub?: boolean;
  isLogisticsHub?: boolean;
}

